const LanguageContext = createContext(null)
const dynamicTranslations = Object.entries(translations)
  .filter(([key]) => /\{\w+\}/.test(key))
  .map(([key, english]) => {
    const names = []
    const source = key.split(/(\{\w+\})/g).map(part => {
      if (/^\{\w+\}$/.test(part)) {
        names.push(part.slice(1, -1))
        return '(.+?)'
      }
      return part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    }).join('')
    return { expression: new RegExp(`^${source}$`), names, english }
  })
export const hasEnglishTranslation = key => Object.hasOwn(translations, key)
export function translate(key, language = 'es', params = {}) {
  if (typeof key !== 'string') return key
  if (language !== 'en') return key.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''))
  let english = translations[key]
  let values = params
  if (!english) {
    for (const entry of dynamicTranslations) {
      const match = entry.expression.exec(key)
      if (match) {
        english = entry.english
        values = { ...Object.fromEntries(entry.names.map((name, index) => [name, match[index + 1]])), ...params }
        break
      }
    }
  }
  return (english || key).replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''))
}
const spanishDefaults = {
  language: 'es', locale: 'es-EC',
  t: (key, params = {}) => translate(key, 'es', params),
  setLanguage: () => {},
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try { return (localStorage.getItem(STORAGE_KEY) || localStorage.getItem(LEGACY_STORAGE_KEY)) === 'en' ? 'en' : 'es' }
    catch { return 'es' }
  })
  useEffect(() => {
    document.documentElement.lang = language
    try { localStorage.setItem(STORAGE_KEY, language) } catch { /* Storage may be disabled. */ }
  }, [language])
  const value = useMemo(() => ({
    language, setLanguage,
    t: (key, params = {}) => translate(key, language, params),
    locale: language === 'en' ? 'en-US' : 'es-EC',
  }), [language])
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  return useContext(LanguageContext) || spanishDefaults
}

export function LanguageSelector() {
  const { language, setLanguage } = useLanguage()
  return <label className="flex shrink-0 items-center gap-1 text-sm font-semibold">
    <span className="sr-only">{language === 'en' ? 'Language' : 'Idioma'}</span>
    <select aria-label={language === 'en' ? 'Language' : 'Idioma'} value={language}
      onChange={event => setLanguage(event.target.value)}
      className="rounded-lg border border-line bg-white px-2 py-2 text-ink focus-visible:outline focus-visible:outline-2 focus-visible:outline-leaf">
      <option value="es">🇪🇨 ES</option><option value="en">🇺🇸 EN</option>
    </select>
  </label>
}
